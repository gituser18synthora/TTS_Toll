"""SQLAlchemy ORM models. All *_path columns are relative to DATA_ROOT."""
from __future__ import annotations

import json
from datetime import datetime, timezone

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Integer, LargeBinary, String, Text, UniqueConstraint
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def utcnow() -> datetime:
    """Naive UTC timestamp (SQLite has no tz support); serialized with a trailing Z."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


class Base(DeclarativeBase):
    pass


# AUTOINCREMENT: ids are never reused, e.g. clips regenerated by "reprocess" get new ids,
# so old export manifests and logs never point at a different clip.
_NO_REUSE = {"sqlite_autoincrement": True}


class Speaker(Base):
    __tablename__ = "speakers"
    __table_args__ = _NO_REUSE

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    gender: Mapped[str] = mapped_column(String(16))
    notes: Mapped[str | None] = mapped_column(Text, default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)


class SourceFile(Base):
    __tablename__ = "source_files"
    __table_args__ = _NO_REUSE

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    original_path: Mapped[str] = mapped_column(String(512))
    original_filename: Mapped[str] = mapped_column(String(256))
    original_sha256: Mapped[str | None] = mapped_column(String(64), index=True, default=None)
    original_size: Mapped[int | None] = mapped_column(Integer, default=None)
    converted_path: Mapped[str | None] = mapped_column(String(512), default=None)
    enhanced_path: Mapped[str | None] = mapped_column(String(512), default=None)
    # NULL for multi-speaker files: their clips get speakers from the diarization labels (speaker_map)
    speaker_id: Mapped[int | None] = mapped_column(ForeignKey("speakers.id"), index=True, nullable=True)
    language: Mapped[str] = mapped_column(String(16), index=True)
    duration: Mapped[float | None] = mapped_column(Float, default=None)
    # uploaded | processing | needs_speakers (waiting for diarization labels to be named) | done | failed
    status: Mapped[str] = mapped_column(String(16), default="uploaded", index=True)
    stage: Mapped[str | None] = mapped_column(String(32), default=None)  # step currently / last running
    steps_done: Mapped[str] = mapped_column(Text, default="[]")  # JSON list of completed pipeline steps
    progress: Mapped[float] = mapped_column(Float, default=0.0)  # 0..100
    error: Mapped[str | None] = mapped_column(Text, default=None)
    notes: Mapped[str | None] = mapped_column(Text, default=None)
    multi_speaker: Mapped[bool] = mapped_column(Boolean, default=False)
    # JSON {diarization label: {"speaker_id": id} | {"ignore": true}} for multi-speaker files
    speaker_map: Mapped[str | None] = mapped_column(Text, default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow, onupdate=utcnow)

    speaker: Mapped[Speaker | None] = relationship(lazy="joined")

    def get_speaker_map(self) -> dict:
        try:
            return dict(json.loads(self.speaker_map or "{}"))
        except ValueError:
            return {}

    def get_steps_done(self) -> list[str]:
        try:
            return list(json.loads(self.steps_done or "[]"))
        except ValueError:
            return []


class Clip(Base):
    __tablename__ = "clips"
    __table_args__ = (UniqueConstraint("source_file_id", "idx", name="uq_clip_source_idx"), _NO_REUSE)

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    source_file_id: Mapped[int] = mapped_column(ForeignKey("source_files.id"), index=True)
    speaker_id: Mapped[int] = mapped_column(ForeignKey("speakers.id"), index=True)
    language: Mapped[str] = mapped_column(String(16), index=True)
    idx: Mapped[int] = mapped_column(Integer)  # order within the source file
    clip_path: Mapped[str] = mapped_column(String(512))
    start_time: Mapped[float] = mapped_column(Float)  # seconds in the source recording
    end_time: Mapped[float] = mapped_column(Float)
    duration: Mapped[float] = mapped_column(Float, index=True)
    text: Mapped[str | None] = mapped_column(Text, default=None)  # editable / final transcript
    text_edited: Mapped[bool] = mapped_column(Boolean, default=False)
    asr_primary_text: Mapped[str | None] = mapped_column(Text, default=None)  # NULL = not transcribed yet
    asr_secondary_text: Mapped[str | None] = mapped_column(Text, default=None)
    asr_agreement: Mapped[float | None] = mapped_column(Float, default=None, index=True)  # WER primary vs secondary
    asr_confidence: Mapped[float | None] = mapped_column(Float, default=None)  # primary avg log-prob
    asr_primary_engine: Mapped[str | None] = mapped_column(String(64), default=None)  # e.g. faster-whisper:large-v3
    asr_secondary_engine: Mapped[str | None] = mapped_column(String(64), default=None)  # e.g. indicconformer:ctc
    quality_score: Mapped[float | None] = mapped_column(Float, default=None, index=True)  # DNSMOS OVRL (1-5)
    quality_info: Mapped[str | None] = mapped_column(Text, default=None)  # JSON: method, sig, bak, snr, music, babble
    loudness_lufs: Mapped[float | None] = mapped_column(Float, default=None)  # measured before normalization
    needs_review: Mapped[bool] = mapped_column(Boolean, default=False, index=True)
    review_reason: Mapped[str | None] = mapped_column(String(256), default=None)  # comma-separated flags
    status: Mapped[str] = mapped_column(String(16), default="pending", index=True)  # pending|approved|rejected
    reject_reason: Mapped[str | None] = mapped_column(String(64), default=None)
    audio_hash: Mapped[str | None] = mapped_column(String(64), default=None, index=True)
    duplicate_of: Mapped[int | None] = mapped_column(Integer, default=None)  # clip kept instead of this one
    speaker_label: Mapped[str | None] = mapped_column(String(32), default=None)  # diarization label (multi-speaker)
    speaker_similarity: Mapped[float | None] = mapped_column(Float, default=None)  # cosine to the speaker centroid
    speaker_embedding: Mapped[bytes | None] = mapped_column(LargeBinary, default=None, deferred=True)  # float16[256]
    reviewed_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow, onupdate=utcnow)

    speaker: Mapped[Speaker] = relationship(lazy="joined")
    source_file: Mapped[SourceFile] = relationship(lazy="joined")

    def flags(self) -> list[str]:
        return [f for f in (self.review_reason or "").split(",") if f]

    def set_flags(self, flags: list[str] | set[str]) -> None:
        self.review_reason = ",".join(sorted(set(flags))) or None


class Job(Base):
    __tablename__ = "jobs"
    __table_args__ = _NO_REUSE

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    type: Mapped[str] = mapped_column(String(32))  # process | export
    source_file_id: Mapped[int | None] = mapped_column(ForeignKey("source_files.id"), index=True, default=None)
    export_id: Mapped[int | None] = mapped_column(ForeignKey("exports.id"), index=True, default=None)
    status: Mapped[str] = mapped_column(String(16), default="queued", index=True)  # queued|running|done|failed|cancelled
    progress: Mapped[float] = mapped_column(Float, default=0.0)  # 0..100
    message: Mapped[str | None] = mapped_column(String(256), default=None)
    log: Mapped[str] = mapped_column(Text, default="")
    params: Mapped[str | None] = mapped_column(Text, default=None)  # JSON
    error: Mapped[str | None] = mapped_column(Text, default=None)
    worker_id: Mapped[str | None] = mapped_column(String(128), default=None)
    cancel_requested: Mapped[bool] = mapped_column(Boolean, default=False)
    heartbeat_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    started_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)
    finished_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)

    def get_params(self) -> dict:
        try:
            return dict(json.loads(self.params or "{}"))
        except ValueError:
            return {}


class Export(Base):
    __tablename__ = "exports"
    __table_args__ = _NO_REUSE

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(128), index=True)
    params: Mapped[str] = mapped_column(Text, default="{}")  # JSON
    status: Mapped[str] = mapped_column(String(16), default="queued")  # queued|running|done|failed
    out_dir: Mapped[str | None] = mapped_column(String(512), default=None)
    zip_path: Mapped[str | None] = mapped_column(String(512), default=None)
    clip_count: Mapped[int] = mapped_column(Integer, default=0)
    total_duration: Mapped[float] = mapped_column(Float, default=0.0)
    stats: Mapped[str | None] = mapped_column(Text, default=None)  # JSON
    error: Mapped[str | None] = mapped_column(Text, default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    finished_at: Mapped[datetime | None] = mapped_column(DateTime, default=None)


class WorkerInfo(Base):
    """Liveness of worker processes, so the UI can warn when no worker is running."""
    __tablename__ = "workers"

    id: Mapped[str] = mapped_column(String(128), primary_key=True)  # host:pid
    device: Mapped[str | None] = mapped_column(String(32), default=None)
    info: Mapped[str | None] = mapped_column(Text, default=None)  # JSON
    started_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
    heartbeat_at: Mapped[datetime] = mapped_column(DateTime, default=utcnow)
